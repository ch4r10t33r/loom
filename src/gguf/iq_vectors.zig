//! Golden vectors for the codebook (IQ / MXFP4) decoders, produced by
//! llama.cpp's own `dequantize_row_*` functions in `ggml/src/ggml-quants.c`.
//!
//! Why this exists: a codebook decoder that mis-shifts an index or reads the
//! wrong grid does not crash and does not produce obviously-wrong numbers — it
//! produces plausible garbage, and the model just gets quietly worse. Unit
//! tests written against our own understanding of the format cannot catch
//! that, because they encode the same understanding. These vectors come from
//! the reference implementation, so they do.
//!
//! Inputs are deterministic pseudo-random block bytes; expected outputs are
//! stored as raw f32 bit patterns so the comparison is exact rather than
//! approximate. Regenerate only against an upstream llama.cpp checkout.

